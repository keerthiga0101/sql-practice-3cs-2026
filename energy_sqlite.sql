-- Display energy records
SELECT record_date, energy_source, generated_energy,
       consumed_energy, location
FROM ENERGY_DATA
ORDER BY record_date, location;

-- Total energy generated by each energy source
SELECT energy_source, SUM(generated_energy) AS total_generated
FROM ENERGY_DATA
GROUP BY energy_source;

-- Daily energy consumption
SELECT record_date, SUM(consumed_energy) AS daily_consumption
FROM ENERGY_DATA
GROUP BY record_date
ORDER BY record_date;

-- Energy surplus or deficit for each record
SELECT record_id, location, generated_energy, consumed_energy,
       (generated_energy - consumed_energy) AS balance,
       CASE
           WHEN generated_energy > consumed_energy THEN 'Surplus'
           WHEN generated_energy < consumed_energy THEN 'Deficit'
           ELSE 'Balanced'
       END AS status
FROM ENERGY_DATA;

-- Total energy generation for each location
SELECT location, SUM(generated_energy) AS total_generation
FROM ENERGY_DATA
GROUP BY location
ORDER BY total_generation DESC;
